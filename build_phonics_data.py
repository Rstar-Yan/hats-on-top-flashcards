# IPA -> 前端 slug（必须和 index.html 的 IPA_SLUG 一致）
IPA_SLUG = {
 'æ':'a','e':'e','ɪ':'i','ɒ':'o','ʌ':'u','ʊ':'oo-short','ə':'er','i':'ee',
 'iː':'ee','uː':'oo','eɪ':'ai','aɪ':'ie','əʊ':'oa','aʊ':'ou','ɔɪ':'oi',
 'ɔː':'or','ɑː':'ar','ɜː':'er','juː':'ue',
 'b':'b','d':'d','f':'f','g':'g','h':'h','dʒ':'j','k':'k','l':'l','m':'m',
 'n':'n','ŋ':'ng','p':'p','r':'r','s':'s','t':'t','v':'v','w':'w','j':'y',
 'z':'z','ʃ':'sh','tʃ':'ch','θ':'th','ð':'th2','kw':'qu','ts':'ts','ks':'x',
}

HERE = os.path.dirname(os.path.abspath(__file__))
AUDIO = os.path.join(HERE, 'phonics')

out, errs, n_ok, n_skip = {}, [], 0, 0
for uid, u in U.items():
    words = {}
    for w, blocks in u['words'].items():
        if blocks is None:
            words[w] = None; n_skip += 1; continue
        joined = ''.join(g for g, _ in blocks)
        if joined != w:
            errs.append(f"U{uid} {w}: 拼写对不上 -> {joined}")
            words[w] = None; n_skip += 1; continue
        bad = [p for _, p in blocks if p and (p not in IPA_SLUG or
               not os.path.exists(os.path.join(AUDIO, IPA_SLUG[p] + '.mp3')))]
        if bad:
            errs.append(f"U{uid} {w}: 音素缺音频 {bad}")
        words[w] = blocks; n_ok += 1
    out[str(uid)] = {'title': u['title'], 'words': words}

print(f"可拼读 {n_ok} 词，跳过 {n_skip} 词")
if errs:
    print("\n".join(errs))
    sys.exit(1)
json.dump({'units': out}, open(os.path.join(HERE, 'phonics.json'), 'w'),
          ensure_ascii=False, indent=1)
